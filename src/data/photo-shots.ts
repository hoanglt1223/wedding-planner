export function getTemplatePhotoShots(lang: string): PhotoShot[] {
  const en = lang === "en";
  return TEMPLATE_SHOTS.map((shot, index) => ({
    ...shot,
    id: index + 1,
    description: en ? shot.descriptionEn : shot.descriptionVi,
    title: en ? shot.titleEn : shot.titleVi,
  }));
}

